// Daily Puzzle Seed Generator based on Calendar Date (resets automatically at midnight)
export function getDailyWordTarget(useNaijaWords: boolean = true): { word: string; dateStr: string; puzzleNumber: number } {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  const dateStr = `${year}-${month}-${day}`;

  // Deterministic seed
  const dayIndex = Math.floor((now.getTime() - new Date(2025, 0, 1).getTime()) / (1000 * 60 * 60 * 24));
  const pool = useNaijaWords
    ? [...NAIJA_5_LETTER_WORDS, ...COMMON_5_LETTER_ANSWERS]
    : COMMON_5_LETTER_ANSWERS;

  const word = pool[Math.abs(dayIndex) % pool.length].toUpperCase();
  return {
    word,
    dateStr,
    puzzleNumber: Math.max(1, dayIndex),
  };
}
